def score_to_grade(s: float) -> str:
    if s >= 70: return '정상'
    if s >= 50: return '관심'
    if s >= 35: return '주의'
    if s >= 20: return '경계'
    return '위기'


def get_ind_probs(size_cd: str, region_cd: str) -> list:
    base = list(IND_PROB[size_cd])
    if region_cd in DAEGU_GYEONGBUK_REGIONS:
        for i, ind in enumerate(INDUSTRIES):
            if ind in DAEGU_IND_BOOST:
                base[i] *= DAEGU_IND_BOOST[ind]
        total = sum(base)
        return [x / total for x in base]
    return base
